/**
 * Generates the harness clients from the ONE tool manifest (lib/agents/tools.ts).
 *   packages/harness/client/manifest.json   — the manifest as data (MCP server reads it)
 *   packages/harness/client/index.mjs       — TypeScript-typed JS client (fetch only, zero deps)
 *   packages/harness/client/index.d.ts      — types
 *   packages/harness/python/harness_talk.py — Python twin (stdlib only)
 * Run after any change to the manifest. The MCP server and daemon are hand-written but read manifest.json.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const { TOOLS, buildToolManifest } = await import("../lib/agents/tools.ts");

const root = resolve(import.meta.dirname, "..", "packages", "harness");
mkdirSync(resolve(root, "client"), { recursive: true });
mkdirSync(resolve(root, "python"), { recursive: true });

const manifest = buildToolManifest("https://harness.talk");
writeFileSync(resolve(root, "client", "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");

// ---- JS client -------------------------------------------------------------
const jsMethods = TOOLS.map((t) => {
  const pathParams = [...t.path.matchAll(/\{(\w+)\}/g)].map((m) => m[1]);
  const queryParams = Object.keys(t.inputSchema.properties ?? {}).filter((k) => !pathParams.includes(k));
  return `
  /** ${t.description.replace(/\*\//g, "* /")} */
  async ${t.name}(input) {
    ${pathParams.map((p) => `if (input?.${p} == null) throw new HarnessError({ title: "ref_unparseable", status: 400, detail: "Missing required '${p}'" });`).join("\n    ")}
    let path = ${JSON.stringify(t.path)}${pathParams.map((p) => `.replace("{${p}}", encodeURIComponent(String(input.${p})))`).join("")};
    const q = new URLSearchParams();
    ${queryParams.map((k) => `if (input?.${k} != null) q.set(${JSON.stringify(k)}, String(input.${k}));`).join("\n    ")}
    const qs = q.toString();
    return this._get(path + (qs ? "?" + qs : ""));
  },`;
}).join("\n");

const jsClient = `// SPDX-License-Identifier: LGPL-3.0-or-later
// Generated by scripts/build-harness.mjs from lib/agents/tools.ts — do not edit by hand.
// Zero dependencies. Works in Node 20+, Deno, Bun, browsers, and edge runtimes.

export class HarnessError extends Error {
  constructor(problem) {
    super(problem.detail || problem.title || "harness error");
    this.name = "HarnessError";
    this.problem = problem;
    this.code = problem.title;
    this.status = problem.status;
  }
}

const DEFAULTS = {
  baseUrl: "https://harness.talk",
  /** Try the loopback daemon first for resolveQuartet (127.b.c.v:1611). Set false to skip. */
  preferLocal: true,
  localPort: 1611,
  fetch: globalThis.fetch,
  timeoutMs: 15000,
};

async function sha256Hex(s) {
  const data = new TextEncoder().encode(s);
  if (globalThis.crypto?.subtle) {
    const buf = await crypto.subtle.digest("SHA-256", data);
    return [...new Uint8Array(buf)].map((b) => b.toString(16).padStart(2, "0")).join("");
  }
  const { createHash } = await import("node:crypto");
  return createHash("sha256").update(data).digest("hex");
}

/** Recompute a verse's hash and compare. Returns true only on an exact match. */
export async function verify(verse) {
  if (!verse || typeof verse.text !== "string") return false;
  // Canonical leaf: sha256(ref + "\\n" + text) — identical to the corpus Merkle leaves.
  const h = await sha256Hex(\`\${verse.ref}\\n\${verse.text}\`);
  return h === verse.sha256;
}

export function createClient(options = {}) {
  const o = { ...DEFAULTS, ...options };
  const client = {
    options: o,

    async _get(path, base = o.baseUrl) {
      const ctrl = new AbortController();
      const t = setTimeout(() => ctrl.abort(), o.timeoutMs);
      try {
        const r = await o.fetch(base + path, { headers: { accept: "application/json" }, signal: ctrl.signal });
        const body = await r.json().catch(() => ({ title: "not_found", status: r.status, detail: "Non-JSON response" }));
        if (!r.ok) throw new HarnessError(body);
        return body;
      } finally {
        clearTimeout(t);
      }
    },
${jsMethods}

    /** Verify a verse object returned by any method. */
    verify,

    /** Download the full corpus as an array of verse objects (~4.5 MB). */
    async exportCorpus() {
      const r = await o.fetch(o.baseUrl + "/exports/kjv.jsonl.gz");
      if (!r.ok) throw new HarnessError({ title: "not_found", status: r.status, detail: "Export unavailable" });
      const ds = new DecompressionStream("gzip");
      const text = await new Response(r.body.pipeThrough(ds)).text();
      return text.split("\\n").filter(Boolean).map((l) => JSON.parse(l));
    },
  };

  // resolveQuartet: local daemon first, then hosted — identical JSON either way.
  const hosted = client.resolveQuartet.bind(client);
  client.resolveQuartet = async function (input) {
    if (o.preferLocal && typeof input?.quartet === "string" && /^127\\.\\d+\\.\\d+\\.\\d+$/.test(input.quartet)) {
      try {
        return await client._get("/", \`http://\${input.quartet}:\${o.localPort}\`);
      } catch (e) {
        if (e instanceof HarnessError) throw e; // daemon answered with a problem — respect it
        // network error: no daemon here, fall back to hosted
      }
    }
    return hosted(input);
  };

  return client;
}

export default createClient;
`;
writeFileSync(resolve(root, "client", "index.mjs"), jsClient);

// ---- d.ts -------------------------------------------------------------------
const schemaToTs = (schema) => {
  const props = schema.properties ?? {};
  const req = new Set(schema.required ?? []);
  return "{ " + Object.entries(props).map(([k, v]) => `${k}${req.has(k) ? "" : "?"}: ${v.type === "integer" ? "number" : v.type}`).join("; ") + " }";
};
const dts = `// SPDX-License-Identifier: LGPL-3.0-or-later
// Generated by scripts/build-harness.mjs — do not edit by hand.
export interface Problem { type?: string; title: string; status: number; detail?: string; [k: string]: unknown }
export class HarnessError extends Error { problem: Problem; code: string; status: number; constructor(p: Problem) }
export interface Verse { ref: string; display: string; book: string; chapter: number; verse: number; text: string; source: string; sha256: string; quartet: string }
export interface VerseRange { ref: string; display: string; count: number; verses: Verse[] }
export interface Chapter { ref: string; display: string; book: string; chapter: number; title?: string; headings?: { before: number; text: string }[]; prev: string | null; next: string | null; quartet: string; source: string; verses: Verse[] }
export interface SearchResult { query: string; mode: "reference" | "phrase" | "terms"; total: number; hits: (Verse & { score: number })[]; limit: number; offset: number }
export interface Annotation { id: string; kind: string; ref: string; text: string; anchor?: string; targets?: string[]; source: string }
export interface Annotations { ref: string; source: string; count: number; annotations: Annotation[]; status?: string }
export interface ClientOptions { baseUrl?: string; preferLocal?: boolean; localPort?: number; fetch?: typeof fetch; timeoutMs?: number }
export function verify(verse: Pick<Verse, "source" | "ref" | "text" | "sha256">): Promise<boolean>;
export interface HarnessClient {
  options: Required<ClientOptions>;
${TOOLS.map((t) => `  /** ${t.description.replace(/\*\//g, "* /")} */\n  ${t.name}(input: ${schemaToTs(t.inputSchema)}): Promise<${{ getVerse: "Verse | VerseRange", getPassage: "Chapter", search: "SearchResult", getAnnotations: "Annotations", resolveQuartet: "Verse | Chapter | Record<string, unknown>" }[t.name] ?? "unknown"}>;`).join("\n")}
  verify: typeof verify;
  exportCorpus(): Promise<Verse[]>;
}
export function createClient(options?: ClientOptions): HarnessClient;
export default createClient;
`;
writeFileSync(resolve(root, "client", "index.d.ts"), dts);

// ---- Python twin --------------------------------------------------------------
const pyMethods = TOOLS.map((t) => {
  const pathParams = [...t.path.matchAll(/\{(\w+)\}/g)].map((m) => m[1]);
  const allParams = Object.keys(t.inputSchema.properties ?? {});
  const req = new Set(t.inputSchema.required ?? []);
  const sig = allParams.map((k) => (req.has(k) ? `${k}` : `${k}=None`)).join(", ");
  const queryParams = allParams.filter((k) => !pathParams.includes(k));
  return `
    def ${t.name}(self${sig ? ", " + sig : ""}):
        """${t.description.replace(/"/g, "'")}"""
        path = ${JSON.stringify(t.path)}${pathParams.map((p) => `.replace("{${p}}", quote(str(${p}), safe=""))`).join("")}
        params = {k: v for k, v in {${queryParams.map((k) => `"${k}": ${k}`).join(", ")}}.items() if v is not None}
        ${t.name === "resolveQuartet" ? `if self.prefer_local and re.match(r"^127\\.\\d+\\.\\d+\\.\\d+$", str(quartet)):
            try:
                return self._get("/", base=f"http://{quartet}:{self.local_port}")
            except HarnessError:
                raise
            except (OSError, urllib.error.URLError):
                pass  # no daemon here; fall back to hosted
        ` : ""}return self._get(path, params)`;
}).join("\n");

const py = `# SPDX-License-Identifier: LGPL-3.0-or-later
# Generated by scripts/build-harness.mjs from lib/agents/tools.ts — do not edit by hand.
# Stdlib only. Python 3.9+.
import hashlib
import json
import re
import urllib.error
import urllib.parse
import urllib.request
from urllib.parse import quote


class HarnessError(Exception):
    def __init__(self, problem):
        super().__init__(problem.get("detail") or problem.get("title") or "harness error")
        self.problem = problem
        self.code = problem.get("title")
        self.status = problem.get("status")


def verify(verse) -> bool:
    """Recompute a verse's sha256 and compare. True only on exact match."""
    if not isinstance(verse, dict) or not isinstance(verse.get("text"), str):
        return False
    h = hashlib.sha256(f"{verse['ref']}\\n{verse['text']}".encode()).hexdigest()
    return h == verse.get("sha256")


class Harness:
    def __init__(self, base_url="https://harness.talk", prefer_local=True, local_port=1611, timeout=15):
        self.base_url = base_url.rstrip("/")
        self.prefer_local = prefer_local
        self.local_port = local_port
        self.timeout = timeout

    def _get(self, path, params=None, base=None):
        url = (base or self.base_url) + path
        if params:
            url += "?" + urllib.parse.urlencode(params)
        req = urllib.request.Request(url, headers={"accept": "application/json"})
        try:
            with urllib.request.urlopen(req, timeout=self.timeout) as r:
                return json.load(r)
        except urllib.error.HTTPError as e:
            try:
                raise HarnessError(json.load(e))
            except json.JSONDecodeError:
                raise HarnessError({"title": "not_found", "status": e.code, "detail": "Non-JSON response"})
${pyMethods}

    verify = staticmethod(verify)
`;
writeFileSync(resolve(root, "python", "harness_talk.py"), py);

console.log(`harness generated: ${TOOLS.length} tools → client/index.mjs, client/index.d.ts, client/manifest.json, python/harness_talk.py`);
